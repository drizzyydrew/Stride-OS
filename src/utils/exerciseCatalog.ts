export function resolveExerciseMetadata(input: ExerciseMetadataInput): ExerciseMetadata {
  const raw=input.name?.trim() || EXERCISE_ID_NAMES[input.id??''] || CATALOG_EXERCISE_NAMES.find(item=>`library_${normalizedExerciseIdentityName(item).replace(/[^a-z0-9]+/g,'_')}`===input.id) || '';
  const name=normalizedExerciseIdentityName(raw);
  const recognized=CATALOG_EXERCISE_NAMES.some(item=>normalizedExerciseIdentityName(item)===name);
  const family=recognized ? FAMILIES.find(item=>item.test.test(name)) : undefined;
  const key=name || input.id?.trim() || 'unknown';
  const equipment=input.equipment ? typeof input.equipment==='string'?[input.equipment]:[...input.equipment] : declaredEquipment(raw);
  const result:ExerciseMetadata={canonicalId:`library_${key.replace(/[^a-z0-9]+/g,'_')}`, name:raw,
    primaryMuscles:family?.primary??[], supportMuscles:family?.support??[], mobilityTargets:family?.targets??[], equipment:family?equipment:[],
    category:family?.category??'full_body', movementPattern:family?.pattern??'isometric',kind:family?.kind??'unknown',
    setup:SETUP_DETAILS[name]??family?.setup??'Use your own repeatable setup and record the actual work performed.', benefit:family?.benefit??'Custom movement: muscle attribution is not inferred from an unfamiliar name.',
    adjustment:family?.kind==='mobility' ? 'Use less range or a shorter hold if uncomfortable; extend only when the current dose remains comfortable. Do not force a stretch.'
      : family?.kind==='power' ? 'Begin with low controlled contacts. Reduce height, contacts or complexity if control or next-day tolerance worsens; avoid automatic loaded or depth-jump progressions.'
      : 'Repeat a manageable dose. When all work is controlled and tolerated, change one variable at a time; use less load, range, reps or more support when needed.', known:Boolean(family)};
  return result;
}
