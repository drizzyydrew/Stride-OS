#!/usr/bin/env python3
"""Outline only the frozen legacy 5K lettering; fonts are build tooling only."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
REVISION = "c8e90c6"
FONT = Path("/System/Library/Fonts/Avenir Next.ttc")
NS = "{http://www.w3.org/2000/svg}"
KEYS = ("number", "unit", "title0", "title1", "wordmark")


def ink_bounds(markup, directory):
    svg = Path(directory) / "ink.svg"
    png = Path(directory) / "ink.png"
    svg.write_text('<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100">' + markup + '</svg>')
    subprocess.run(["sips", "-s", "format", "png", "-z", "4096", "4096", str(svg), "--out", str(png)], check=True, stdout=subprocess.DEVNULL)
    alpha = Image.open(png).convert("RGBA").getchannel("A")
    return alpha.point(lambda value: 255 if value >= 16 else 0).getbbox()


def frozen(file):
    return subprocess.check_output(["git", "show", f"{REVISION}:{file}"], cwd=ROOT)


def generate():
    source_path = "assets/achievements/challenges/challenges-5k-month-unlocked.svg"
    source = frozen(source_path)
    elements = list(ET.fromstring(source).iter(f"{NS}text"))
    assert len(elements) == len(KEYS)
    paths = {}
    entries = []
    for key, element in zip(KEYS, elements):
        attrs = dict(element.attrib)
        assert attrs["text-anchor"] == "middle"
        assert attrs["font-family"] == "'Avenir Next', Inter, Arial, sans-serif"
        source_weight = int(attrs["font-weight"])
        assert source_weight in (800, 900)
        text = element.text
        entries.append({"key": key, "text": text, "attributes": dict(element.attrib)})
    outlined = json.loads(subprocess.check_output(
        ["swift", str(HERE / "outline.swift")], input=json.dumps(entries).encode(), cwd=ROOT
    ))
    paths = {item["key"]: {"text": item["text"], "d": item["d"]} for item in outlined}
    # Keep the legacy SVG exporter's actual anchor placement, rather than
    # silently recentering its Heavy ink using CTLine's different advances.
    with tempfile.TemporaryDirectory(prefix="strideos-legacy-outline-") as directory:
        for key, element in zip(KEYS, elements):
            original = ink_bounds(ET.tostring(element, encoding="unicode").replace("ns0:", "").replace(":ns0", ""), directory)
            current = ink_bounds(f'<path d="{paths[key]["d"]}"/>', directory)
            dx = ((original[0] + original[2]) - (current[0] + current[2])) * 100 / 8192
            dy = ((original[1] + original[3]) - (current[1] + current[3])) * 100 / 8192
            paths[key]["transform"] = f"translate({dx} {dy})"
            entries[KEYS.index(key)]["checkpointInkBounds4096"] = original
            entries[KEYS.index(key)]["anchorTranslation"] = [dx, dy]
    sources = {
        file: hashlib.sha256(frozen(file)).hexdigest()
        for state in ("unlocked", "locked", "transparent")
        for ext in ("svg", "png")
        for file in (f"assets/achievements/challenges/challenges-5k-month-{state}.{ext}",)
    }
    output = (
        "// Generated by scripts/legacy-challenge-typography/generate.py.\n"
        "// Frozen legacy lettering; no runtime font lookup or font binary.\n"
        "export const LEGACY_CHALLENGE_LETTERING = " + json.dumps(paths, indent=2) + " as const;\n"
    )
    manifest = {
        "revision": REVISION, "sources": sources, "entries": entries,
        "font": {"path": str(FONT), "sha256": hashlib.sha256(FONT.read_bytes()).hexdigest()},
        "resolvedFonts": {item["key"]: item["font"] for item in outlined},
        "advances": {item["key"]: item["advance"] for item in outlined},
        "engine": "system CoreText CTLine/CTFont glyph paths; tooling only",
    }
    return output, json.dumps(manifest, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output, manifest = generate()
    for file, contents in (
        (ROOT / "src/achievements/challenges/legacyTypography.ts", output),
        (HERE / "manifest.json", manifest),
    ):
        if args.check:
            assert file.read_text() == contents, f"Generated legacy lettering drift: {file}"
        else:
            file.write_text(contents)
    print(f'{"Verified" if args.check else "Outlined"} five frozen legacy 5K text runs using verified Avenir Next weights.')


if __name__ == "__main__":
    main()
