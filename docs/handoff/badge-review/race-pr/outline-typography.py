"""Outline new PR-family labels with existing system CoreText badge tooling.
No font binary or runtime font lookup is introduced. Reuses the established
CTLine/CTFont approach from scripts/legacy-challenge-typography/outline.swift.
"""
import argparse, hashlib, json, subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parent
REPO=ROOT.parents[3]
FONT=Path('/System/Library/Fonts/Supplemental/Arial Narrow.ttf')
labels=[('800m','800M','800 METERS'),('1-mile','1MI','1 MILE'),('5k','5K','5K'),('10k','10K','10K'),('half-marathon','HM','HALF MARATHON'),('marathon','MAR','MARATHON')]
entries=[{'key':'newPr','text':'NEW PR','size':8.8,'baseline':68.2,'maximumWidth':46,'tracking':.08}]
for slug,face,title in labels:
 entries.extend([{'key':slug+':face','text':face,'size':14.5,'baseline':39,'maximumWidth':24,'tracking':0}, {'key':slug+':title','text':title,'size':8.8,'baseline':59.8,'maximumWidth':50,'tracking':.05}])
result=json.loads(subprocess.check_output(['swift',str(ROOT/'outline-typography.swift')],input=json.dumps(entries).encode(),cwd=REPO))
by_key={item['key']:item for item in result}
art={'newPr':by_key['newPr'],'badges':{slug:{part:by_key[slug+':'+part] for part in ['face','title']} for slug,_,_ in labels}}
for item in result:
 assert abs((item['bounds'][0]+item['bounds'][2])/2-50)<1e-7
 item['fontHash']=hashlib.sha256(FONT.read_bytes()).hexdigest()
text='// Generated by docs/handoff/badge-review/race-pr/outline-typography.py.\n// CoreText outlines, Arial Narrow Regular; no runtime fonts.\n// Visible ink centered at x=50. Existing Firsts wordmark is reused.\nexport const RACE_PR_TYPOGRAPHY = '+json.dumps(art,separators=(',',':'))+' as const;\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
for path,contents in [(ROOT/'typography.json',json.dumps(art,indent=2)+'\n'),(REPO/'src/achievements/racePr/racePrTypography.ts',text)]:
 if args.check: assert path.read_text()==contents, 'Typography drift: '+str(path)
 else: path.write_text(contents)
print('Verified' if args.check else 'Outlined',len(result),'new PR labels with exact ArialNarrow face; equal visible margins.')
